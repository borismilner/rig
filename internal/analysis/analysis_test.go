// A gate that cannot fail is what PLAN.md section 5i says the previous
// modularity rules were, so every case here is a violation the analyzer has to
// catch, paired with the nearby thing it must not catch.

// tree writes files into a scratch module and runs one analyzer over it.
// Paths are relative, and they matter: Product() reads them.
func run(t *testing.T, a analysis.Analyzer, files map[string]string) (int, string) {
	t.Helper()
	dir := t.TempDir()
	for name, body := range files {
		p := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	var out, errs strings.Builder
	code, err := analysis.Run(a, []string{dir}, &out, &errs)
	if err != nil {
		t.Fatalf("run: %v", err)
	}
	return code, out.String() + errs.String()
}

func wantFail(t *testing.T, code int, out, substr string) {
	t.Helper()
	if code == 0 {
		t.Fatalf("wanted a failure, got a pass.\n%s", out)
	}
	if !strings.Contains(out, substr) {
		t.Fatalf("wanted %q in the report, got:\n%s", substr, out)
	}
}

func wantPass(t *testing.T, code int, out string) {
	t.Helper()
	if code != 0 {
		t.Fatalf("wanted a pass, got a failure:\n%s", out)
	}
}

func TestNoProgramIDCatchesALiteral(t *testing.T) {
	code, out := run(t, analysis.NoProgramID, map[string]string{
		"internal/svc/a.go": "package svc\n\nvar route = \"shelf\"\n",
	})
	wantFail(t, code, out, `names the in-house program "shelf"`)
}

