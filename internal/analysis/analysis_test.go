func TestNoContextFreeMakesWithCancelCostAReason(t *testing.T) {
	src := "package svc\n\nimport \"context\"\n\n" +
		"func f(ctx context.Context) {\n\tc, cancel := context.WithCancel(ctx)\n" +
		"\tdefer cancel()\n\t_ = c\n}\n"
	code, out := run(t, analysis.NoContextFree, map[string]string{"internal/svc/a.go": src})
	wantFail(t, code, out, "no deadline of its own")

	excused := strings.Replace(src, "\tc, cancel :=",
		"\t//rig:allow nocontextfree: the daemon's lifetime, not a call\n\tc, cancel :=", 1)
	code, out = run(t, analysis.NoContextFree, map[string]string{"internal/svc/a.go": excused})
	wantPass(t, code, out)
}

func TestDirectiveTextInsideAStringIsNotADirective(t *testing.T) {
	// The bug this catches was found by running the analyzers over their own
	// tests: every fixture above holds directive text inside a string
	// literal, and a raw line scan read all of them as live exemptions.
	code, out := run(t, analysis.NoProgramID, map[string]string{
		"internal/svc/a.go": "package svc\n\n" +
			"var fixture = \"//rig:allow noprogramid: not a real directive\"\n" +
			"var route = \"shelf\"\n",
	})
	wantFail(t, code, out, `names the in-house program "shelf"`)
	if strings.Contains(out, "stale") {
		t.Fatalf("a directive inside a string is not an exemption, got:\n%s", out)
	}
}

