func TestADirectiveSuppressesAndMustCarryAReason(t *testing.T) {
	code, out := run(t, analysis.NoProgramID, map[string]string{
		"internal/svc/a.go": "package svc\n\n" +
			"//rig:allow noprogramid: the fixture this benchmark measures\n" +
			"var route = \"shelf\"\n",
	})
	wantPass(t, code, out)

	// The same directive with no reason does not match, so it does not excuse.
	code, out = run(t, analysis.NoProgramID, map[string]string{
		"internal/svc/a.go": "package svc\n\n//rig:allow noprogramid:\nvar route = \"shelf\"\n",
	})
	wantFail(t, code, out, `names the in-house program "shelf"`)
}

